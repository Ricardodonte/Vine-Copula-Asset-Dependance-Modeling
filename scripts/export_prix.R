library(quantmod)
start_date <- as.Date("2016-01-01")
end_date   <- as.Date("2025-11-04")
getSymbols(c("SPY", "BTC-USD", "BND"), src = "yahoo", from = start_date, to = end_date)
px <- merge(Ad(SPY), Ad(`BTC-USD`), Ad(BND))
colnames(px) <- c("SPY", "BTC", "BND")
path <- file.path("data", "prix_spy_btc_bnd.csv")
write.zoo(px, path, sep = ",")
cat("Fichier écrit :", normalizePath(path), "\n")
